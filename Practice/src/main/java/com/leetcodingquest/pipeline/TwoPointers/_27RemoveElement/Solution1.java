package com.leetcodingquest.pipeline.TwoPointers._27RemoveElement;

public class Solution1 {
    // время O(n), память O(1)
    // Принимаем массив nums и значение val, которое нужно удалить
    public int removeElement(int[] nums, int val) {
        // Храним количество элементов, не равных val, и индекс следующей позиции для записи
        int k = 0;
        // Перебираем все элементы массива от первого до последнего
        for (int i = 0; i < nums.length; i++) {
            // Проверяем, нужно ли сохранить текущий элемент
            if (nums[i] != val) {
                // Записываем подходящий элемент в начало массива на позиции k
                nums[k] = nums[i];
                // Записываем подходящий элемент в начало массива на позицию k
                k++;
            }   // Завершаем условие: если элемент равен val, пропускаем его
        } // Завершаем цикл после проверки всех элементов массива
        return k;   // Возвращаем количество элементов, которые не равны val
    }

    public static void main(String[] args) {
        // Создаём объект класса, чтобы вызвать нестатический метод
        Solution1 solution = new Solution1();

        int[] nums1 = {3, 2, 2, 3}; // Создаём первый тестовый массив.
        int val1 = 3; // Указываем значение, которое нужно удалить в первом примере.
        int k1 = solution.removeElement(nums1, val1); // Вызываем метод и получаем количество оставшихся элементов.
        System.out.println("Пример 1: k = " + k1); // Выводим количество оставшихся элементов.
        System.out.print("Массив после обработки: "); // Выводим поясняющий текст перед массивом.
        for (int i = 0; i < k1; i++) { // Перебираем только значимые элементы массива.
            System.out.print(nums1[i] + " "); // Выводим очередной элемент из первых k1 позиций.
        } // Завершаем цикл вывода первого примера.
        System.out.println(); // Переходим на новую строку после вывода массива.

        int[] nums2 = {0, 1, 2, 2, 3, 0, 4, 2}; // Создаём второй тестовый массив.
        int val2 = 2; // Указываем значение, которое нужно удалить во втором примере.
        int k2 = solution.removeElement(nums2, val2); // Вызываем метод и получаем количество оставшихся элементов.
        System.out.println("Пример 2: k = " + k2); // Выводим количество оставшихся элементов.
        System.out.print("Массив после обработки: "); // Выводим поясняющий текст перед массивом.
        for (int i = 0; i < k2; i++) { // Перебираем только значимые элементы массива.
            System.out.print(nums2[i] + " "); // Выводим очередной элемент из первых k2 позиций.
        } // Завершаем цикл вывода второго примера.
        System.out.println(); // Переходим на новую строку после вывода массива.

        int[] nums3 = {}; // Создаём третий тестовый массив нулевой длины.
        int val3 = 5; // Указываем значение для удаления в третьем примере.
        int k3 = solution.removeElement(nums3, val3); // Вызываем метод для пустого массива.
        System.out.println("Пример 3: k = " + k3); // Выводим количество оставшихся элементов.
        System.out.print("Массив после обработки: "); // Выводим поясняющий текст перед массивом.
        for (int i = 0; i < k3; i++) { // Цикл не выполнится, потому что k3 равно нулю.
            System.out.print(nums3[i] + " "); // Эта строка не выполнится для пустого массива.
        } // Завершаем цикл вывода третьего примера.
        System.out.println("пустой массив"); // Сообщаем, что значимых элементов нет.
    }
}
