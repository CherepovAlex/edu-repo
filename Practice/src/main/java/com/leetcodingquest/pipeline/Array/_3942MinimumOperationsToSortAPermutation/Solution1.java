package com.leetcodingquest.pipeline.Array._3942MinimumOperationsToSortAPermutation;

import java.util.ArrayDeque;
import java.util.Arrays;

public class Solution1 {
    // время O(n), память O(n)
    // Возвращаем минимальное число операций или -1
    public int minOperations(int[] nums) {
        int n = nums.length;    // Сохраняем длину исходного массива

        boolean normal = true;  // Предполагаем, что массив является обычным циклическим сдигом
        boolean reversed = true;    // Предполагаем, что массив является обратным циклическим сдигом

        int first = nums[0];    // Первый элемент определяет начало последовательности

        for (int i = 0; i < n; i++) {   // Проверяем каждый элемент массива
            if (nums[i] != (first + i) % n){    // Проверяем обычную последовательность с циклическим переходом через n
                normal = false; // Если элемент не подходит, обычный вариант невозможен
            }   // Завершаем проверку обычного вариант для текущего элемента
            if (nums[i] != (first - i + n) % n){    // Проверяем последовательность в обратном направлении
                reversed = false;   // Если элемент не подходит, обратный вариант невозможен
            }   // Завершаем проверку обратного варианта для текущего элемента
        }   // Завершаем проверку исходного массива

        if (!normal && !reversed){  // Если не подходит ни одно направление
            return -1;  // Возвращаем -1: сортировка невозможна
        }   // Завершаем проверку достижимости

        int startState; // Объявляем номер начального состояния BFS

        if (normal){ // Если массив имеет обычное направление
            startState = first; // Состояние A_k имеет номер k, а k равен первому элементу
        } else {    // Иначе массива имеет обратное направление
            int k = (first + 1) % n;    // Для B_k первый элемента равен (k - 1 + n) % n
            startState = n + k; //  Состояния B_k нумеруются от n до 2*n - 1
        }   // Завершаем определение начального состояния

        int totalStates = 2 * n;    // Есть n обычный и n обратных состояний
        int[] distance = new int[totalStates];  // Храним минимальное число операций до каждого состояния
        Arrays.fill(distance, -1);  // Значение -1 означает, что состояние ещё не посещено

        ArrayDeque<Integer> queue = new ArrayDeque<>(); // Создаём очередь BFS
        queue.offer(startState);    // Добавляем начальное состояние в очередь
        distance[startState] = 0;   // До начального состояния нужно ноль операций

        while (!queue.isEmpty()){   // Продолжаем, пока в очереди остаются состояния
            int state = queue.poll();   // Извлекаем состояние с минимальным расстоянием
            int steps = distance[state];    // Получаем число операций до этого состояния

            if (state == 0){    // Состояние 0 означает отсортированный массив A_0
                return steps;   // Возвращаем минимальное количество операций
            }   // Завершаем проверку цели

            int k;  // Объявляем индекс циклического сдвига
            int next;   // Объявляем переменную для следующего состояния

            if (state < n){ //  Если состояние обычное A_k
                k = state;  // Номер состояния совпадает со сдвигом k

                next = (k + 1) % n; // Сдвиг влево переводит A_k в A_(k+1)
                if (distance[next] == -1){  // Проверяем, посещали ли новое состояние
                    distance[next] = steps + 1; // Записываем расстояние до него
                    queue.offer(next);  // Добавляем его в очередь
                }   // Завершаем обработку сдвига обычного состояния

                next = n + k;   // Разворот переводит A_k в B_k
                if (distance[next] == -1){  //   Проверяем, посещали ли обратное состояние
                    distance[next] = steps + 1; // Записываем расстояние до него
                    queue.offer(next);  // Добавляем его в очередь
                }   // Завершаем обработку разворота обычного состояния
            } else {    // Иначе состояние обратное B_k
                k = state - n;  // Получаем индекс обратного состояния

                next = n + (k - 1 + n) % n; //  Сдвиг влево переводит B_k в B_(k-1)
                if (distance[next] == -1){  // Проверяем, посещали ли новое состояние
                    distance[next] = steps + 1; // Записываем расстояние до него
                    queue.offer(next);  // Добавляем его в очередь
                }   // Завершаем обработку сдвига обратного состояния

                next = k;   // Разворот переводит B_k в A_k
                if (distance[next] == -1){  // Проверяем, посещали ли обычное состояние
                    distance[next] = steps + 1; // Записываем расстоние до него
                    queue.offer(next);  // Добавляем его в очередь
                }   // Завершаем обработку разворота обратного состояния
            }   // Завершаем обработку переходов
        }   // Завершаем BFS, если очередь опустела

        return -1;  // Страховочны возрат: цель не найдена
    }

    public static void main(String[] args) {
        int[] nums = {0, 2, 1};
        System.out.println(new Solution1().minOperations(nums));    // 2
        nums = new int[]{1, 0, 2};
        System.out.println(new Solution1().minOperations(nums));    // 2
        nums = new int[]{2, 0, 1, 3};
        System.out.println(new Solution1().minOperations(nums));    // -1
    }
}
