package com.leetcodingquest.pipeline.HashTable._13RomanToInteger;

public class Solution2 {
    // время O(n), память O(1)
    // Метод принимает строку с римскими цифрами и возвращает целое число
    public int romanToInt(String s) {
        // Инициализируем переменную для хранения итогового результата.
        // Начинаем с 0, так как будем складывать/вычитать значения.
        int result = 0;

        // Получаем длину строки, чтобы знать, когда остановиться.
        int length = s.length();

        // Переменная для хранения значения символа, который мы рассматривали на предыдущем шаге (справа).
        // Изначально 0, так как справа от последнего символа ничего нет.
        int previousValue = 0;

        // Запускаем цикл, идя с конца строки (index = length - 1) к началу (index = 0).
        // Это позволяет легко сравнивать текущий символ с тем, что был справа от него.
        for (int i = length - 1; i >= 0; i--) {

            // Преобразуем текущий символ строки в его числовое значение римской цифры.
            // Например, 'M' -> 1000, 'IV' -> 1 и т.д.
            int currentValue = getRomanValue(s.charAt(i));

            // Проверяем: если текущее значение меньше, чем предыдущее (справа),
            // значит, это случай вычитания (например, I перед V в IV).
            // В этом случае мы вычитаем текущее значение из результата.
            if (currentValue < previousValue) {
                result -= currentValue;
            }
            // Иначе (если текущее значение больше или равно предыдущему),
            // мы просто добавляем текущее значение к результату.
            else {
                result += currentValue;
            }

            // Обновляем previousValue для следующей итерации (которая будет слева от текущей).
            // Теперь текущий символ станет "предыдущим" для следующего шага.
            previousValue = currentValue;
        }

        // Возвращаем вычисленное итоговое целое число.
        return result;
    }

    // Вспомогательный метод для получения числового значения римского символа.
    // Используем switch-case для эффективности и читаемости.
    private int getRomanValue(char c) {
        return switch (c) {
            case 'I' -> 1;
            case 'V' -> 5;
            case 'X' -> 10;
            case 'L' -> 50;
            case 'C' -> 100;
            case 'D' -> 500;
            case 'M' -> 1000;
            // По условию задачи входные данные всегда корректны,
            // поэтому default не обязателен, но полезен для безопасности.
            default -> 0;
        };
    }
}
