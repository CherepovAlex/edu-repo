package com.leetcodingquest.pipeline._7ReverseInteger;

public class Solution2 {
        // время O(log10(x)) или O(N), память O(1)
       public int reverse(int x) {
        // Инициализируем переменную для хранения перевернутого числа.
        // Начальное значение 0.
        int rev = 0;

        // Цикл выполняется, пока x не станет равным 0.
        // Это означает, что мы обработали все цифры исходного числа.
        while (x != 0) {
            // Извлекаем последнюю цифру числа x.
            // Оператор % 10 возвращает остаток от деления на 10.
            // Например, если x = 123, то pop = 3.
            // Если x = -123, то pop = -3 (Java сохраняет знак при остатке).
            int pop = x % 10;

            // "Отрезаем" последнюю цифру от x.
            // Оператор / 10 выполняет целочисленное деление.
            // Например, если x = 123, то x становится 12.
            // Если x = -123, то x становится -12.
            x /= 10;

            // ПРОВЕРКА НА ПЕРЕПОЛНЕНИЕ (OVERFLOW CHECK)
            // Мы не можем просто сделать rev = rev * 10 + pop,
            // потому что это может выйти за пределы int.

            // Проверяем, не выйдет ли новое значение за максимальную границу Integer.MAX_VALUE (2147483647)
            // Если rev больше, чем 214748364 (MAX_VALUE / 10), то умножение на 10 гарантированно приведет к переполнению.
            if (rev > Integer.MAX_VALUE / 10 || (rev == Integer.MAX_VALUE / 10 && pop > 7)) {
                // Если переполнение возможно, возвращаем 0, как требует условие задачи.
                return 0;
            }

            // Проверяем, не выйдет ли новое значение за минимальную границу Integer.MIN_VALUE (-2147483648)
            // Если rev меньше, чем -214748364 (MIN_VALUE / 10), то умножение на 10 гарантированно приведет к переполнению.
            if (rev < Integer.MIN_VALUE / 10 || (rev == Integer.MIN_VALUE / 10 && pop < -8)) {
                // Если переполнение возможно, возвращаем 0.
                return 0;
            }

            // Обновляем перевернутое число.
            // Умножаем текущий результат на 10, чтобы сдвинуть цифры влево,
            // и добавляем извлеченную последнюю цифру (pop).
            rev = rev * 10 + pop;
        }

        // Когда цикл завершается, rev содержит перевернутое число.
        // Возвращаем результат.
        return rev;
    }
}
