package com.leetcodingquest.pipeline._3551MinimumSwapsToSortByDigitSum;

import java.util.Arrays;

public class Solution3 {
    public int minSwaps(int[] nums) {
        int n = nums.length;
        // Если массив пуст или из одного элемента, перестановки не нужны
        if (n <= 1) {
            return 0;
        }

        // Создаем массив индексов, которые мы будем сортировать [0, 1, 2, ..., n-1]
        Integer[] indices = new Integer[n];
        for (int i = 0; i < n; i++) {
            indices[i] = i;
        }

        // Сортируем индексы на основе правил сортировки элементов nums
        Arrays.sort(indices, (a, b) -> {
            // Вычисляем суммы цифр для элементов a и b
            int sumA = getDigitSum(nums[a]);
            int sumB = getDigitSum(nums[b]);
            // Если суммы разные, сортируем по возрастанию суммы
            if (sumA != sumB) {
                return Integer.compare(sumA, sumB);
            } else {
                // Если суммы одинаковые, сортируем по возрастанию самих чисел
                return Integer.compare(nums[a], nums[b]);
            }
        });

        // Теперь indices[i] — это индекс элемента в исходном массиве, который должен стоять на позиции i в отсортированном массиве.
        // То есть: sortedNums[i] = nums[indices[i]]

        // Нам нужно найти количество обменов, чтобы привести массив nums к этому состоянию.
        // Это задача о подсчете циклов в перестановке.
        // Перестановка P такова, что P[i] = indices[i].
        // Мы хотим разложить P на циклы. Для цикла длины k нужно k-1 обменов.

        // Создаем массив для отслеживания посещенных элементов
        boolean[] visited = new boolean[n];
        int totalSwaps = 0;

        // Проходим по каждому индексу, чтобы найти циклы в перестановке
        for (int i = 0; i < n; i++) {
            // Если элемент уже был частью какого-то цикла, пропускаем
            if (visited[i]) {
                continue;
            }

            // Если элемент уже стоит на своем месте (nums[i] уже соответствует своему месту в отсортированном массиве)
            // Это означает, что в позиции i отсортированного массива должен быть nums[i].
            // Проверим: если i-й элемент в отсортированном списке — это nums[i], то индексы[i] должен быть равен i.
            if (indices[i] == i) {
                visited[i] = true;
                continue;
            }

            // Начинаем поиск цикла
            int cycleSize = 0;
            int curr = i;
            // Цикл продолжается, пока мы не вернемся к уже посещенному элементу в данном цикле
            while (!visited[curr]) {
                visited[curr] = true;
                cycleSize++;
                // Переходим к следующей позиции в цикле перестановки
                // Если мы хотим, чтобы элемент, который сейчас должен быть на позиции curr (а это nums[indices[curr]]),
                // оказался на месте, куда он должен идти...
                // Давайте посмотрим на структуру циклов для перестановки P:
                // P[i] — это позиция, на которую должен перейти элемент с позиции i? Нет.
                // P[i] = indices[i] — это индекс исходного элемента, который занимает позицию i в отсортированном массиве.
                // Это стандартная форма "позиции i занимает элемент из источника P[i]".
                // Чтобы найти циклы перестановки, которая приводит исходный массив к отсортированному,
                // мы рассматриваем перестановку Q, где Q[i] — это место, куда должен уйти элемент с позиции i.
                // Но здесь проще так:
                // Мы хотим, чтобы в позиции i оказался элемент nums[indices[i]].
                // Пусть curr — это текущая рассматриваемая позиция в исходном массиве.
                // Мы хотим переместить элемент nums[indices[curr]] на позицию curr? Нет.

                // Давайте используем классический подход для "минимальных обменов для сортировки":
                // У нас есть массив arr. Мы хотим получить sortedArr.
                // Мы создаем массив pos, где pos[val] = index в sortedArr.
                // Но здесь значения не уникальны по индексам, а уникальны по значению в исходном массиве?
                // В условии сказано: "nums состоит из различных целых положительных чисел". Отлично!

                // Значит, мы можем использовать значения как ключи.
                // Но в цикле выше мы используем индексы i.
                // indices[i] — это индекс j, такой что nums[j] — это i-й элемент в отсортированном массиве.
                // Это означает, что элемент nums[j] должен оказаться на позиции i.
                // Значит, для элемента с исходным индексом j, целевая позиция i = index в indices, где indices[i] == j.
                // Это обратная перестановка.

                // Давайте переформулируем для ясности.
                // Перестановка P задана массивом indices: P[i] = indices[i].
                // Это значит, что на позицию i в результате должен прийти элемент с индекса P[i] из источника.
                // Минимальное количество обменов для получения такой перестановки из тождественной (1,2,3...)
                // равно N - (количество циклов в разложении перестановки P).
                // Почему? Потому что каждый цикл длины k требует k-1 обмен.
                // Сумма (k-1) по всем циклам = (sum of k) - (number of cycles) = N - C.

                // Таким образом, нам просто нужно найти количество циклов в массиве indices.
                // Массив indices: [0, 1, 2, ...] -> после сортировки становится [idx0, idx1, idx2, ...]
                // Циклы находятся так:
                // i -> indices[i] -> indices[indices[i]] -> ...

                curr = indices[curr];
            }
            // Для цикла длины k требуется k-1 обменов
            if (cycleSize > 1) {
                totalSwaps += (cycleSize - 1);
            }
        }

        return totalSwaps;
    }

    // Вспомогательный метод для вычисления суммы цифр
    private int getDigitSum(int num) {
        int sum = 0;
        while (num > 0) {
            sum += num % 10;
            num /= 10;
        }
        return sum;
    }
    public static void main(String[] args) {
        int[] nums = new int[] {37, 100};
        System.out.println(new Solution3().minSwaps(nums)); // [100, 37], 1
        int[] nums1 = new int[] {18, 43, 34, 16};
        System.out.println(new Solution3().minSwaps(nums1)); // [16, 34, 43, 18], 2
        int[] nums2 = new int[] {22, 14, 33, 7};
        System.out.println(new Solution3().minSwaps(nums2)); // [22, 14, 33, 7], 0
    }
}
