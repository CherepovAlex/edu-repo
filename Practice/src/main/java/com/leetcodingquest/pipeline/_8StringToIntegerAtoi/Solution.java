package com.leetcodingquest.pipeline._8StringToIntegerAtoi;

public class Solution {
    // время O(n), память O(1)
    // Объявляем метод, преобразующий строку в int
    public int myAtoi(String s) {
        if (s == null || s.isEmpty()) return 0; // Если строка null или пустая, возвращаем 0

        int n = s.length(); // Сохраняем длину строки, чтобы не вычислять её повторно
        int i = 0;  // Создаём индекс для чтения символов строки

        while (i < n && s.charAt(i) == ' '){    // Пока не достигнут конец строки и текущий символ - пробел
            i++;        // Пропускаем начальный пробел
        }

        if (i == n) return 0;   // Если после пробелов строка закончилась, возвращаем 0

        int sign = 1;   // По умолчанию считаем число положительным

        if (i < n && s.charAt(i) == '-') {  // Проверяем, есть ли минус после начальных пробелов
            sign = -1;  // Устанавливаем отрицательный знак
            i++;    // Переходим к символу после минуса
        } else if (i < n && s.charAt(i) == '+') { // Иначе проверяем, есть ли плюс
            i++;    // Пропускаем плюс, сохраняя положительный знак
        }   // Завершаем определение знака

        long result = 0;    // Создаём накопитель числа, используя Long для безопасной проверки границ
        long limit = sign == 1  // Выбираем максимально допустимую абсолютную величину
                ? Integer.MAX_VALUE     // Для положительного числа предел равен 2147483647
                : -(long) Integer.MIN_VALUE;    //  Для отрицательного числа предел равен 2147483648

        while (i < n){  // Продолжаем, пока в строке остаются символы
            char c = s.charAt(i);    // Получаем текущий символ цифрой
            if (c < '0' || c > '9'){    // Проверяем, не является ли символ цифрой
                break;  // Прекращаем чтение на первом нецифровом стиле
            }   // Завершаем проверку символа

            int digit = c - '0';    // Преобразуем символ цифры в числовое значение от 0 до 9
            result = result * 10 + digit;   // Прибавляем цифру справа к накопленному числу

            if (result > limit) {   // Проверяем, вышло ли число за допустимую границу
                return sign == 1    // Если число переполнено, выбираем результат по знаку
                        ? Integer.MAX_VALUE  // Ограничиваем положительное число сверху
                        : Integer.MIN_VALUE; // Ограничиваем отрицательное число снизу
            }   // Завершаем проверку переполнения
            i++;    // Переходим к следующему символу после успешной обработки цифры
        }   // Завершаем чтение последовательности цифр
        return (int) (result * sign);   // Применяем знак и возвращаем результат типа int
    }

    public static void main(String[] args) {
        String s = "42";
        System.out.println(new Solution().myAtoi(s)); // 42
        s = " -042";
        System.out.println(new Solution().myAtoi(s)); // -42
        s = "1337c0d3";
        System.out.println(new Solution().myAtoi(s)); // 1337
        s = "0-1";
        System.out.println(new Solution().myAtoi(s)); // 0
        s = "words and 987";
        System.out.println(new Solution().myAtoi(s)); // 0
    }
}
